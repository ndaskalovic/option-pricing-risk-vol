/// Generates `$T<R>` = R × `$m::V` (`$n` lanes of `$e` each) from the register ops in module
/// `$m`: `splat load load_f32 store add sub mul div neg fma fnma sqrt min max sel_gt round scale`,
/// with `fma(a, b, c) = a·b + c`, `fnma(a, b, c) = c − a·b`, `min`/`max` returning the second
/// operand when either is NaN (x86 semantics) and `round` to nearest, plus `exp`, the
/// [`exp_poly`](crate::lanes::exp_poly) constants that match `scale` (`p·2^n` via `bits` or `scalef`).
macro_rules! x86_pack {
    ($(#[$doc:meta])* $T:ident, $e:ident, $n:literal, $m:ident) => {
        $(#[$doc])*
        #[derive(Clone, Copy)]
        pub struct $T<const R: usize>([$m::V; R]);

        impl<const R: usize> $T<R> {
            #[inline(always)]
            fn map(self, f: impl Fn($m::V) -> $m::V) -> Self {
                Self(::std::array::from_fn(|i| f(self.0[i])))
            }
            #[inline(always)]
            fn zip(self, o: Self, f: impl Fn($m::V, $m::V) -> $m::V) -> Self {
                Self(::std::array::from_fn(|i| f(self.0[i], o.0[i])))
            }
            #[inline(always)]
            fn regs(self) -> [[$e; $n]; R] {
                self.0.map(|r| {
                    let mut a = [0.0; $n];
                    unsafe { $m::store(a.as_mut_ptr(), r) };
                    a
                })
            }
            #[inline(always)]
            fn per_lane(self, f: impl Fn($e) -> $e) -> Self {
                self.map(|r| {
                    let mut a = [0.0; $n];
                    unsafe { $m::store(a.as_mut_ptr(), r) };
                    let a = a.map(&f);
                    unsafe { $m::load(a.as_ptr()) }
                })
            }
            /// Polynomial `exp` ([`exp_poly`]($crate::lanes::exp_poly)); NaN propagates.
            #[inline(always)]
            fn exp_reg(x: $m::V) -> $m::V {
                use $m::exp::*;
                use $m::splat;
                let x = $m::min(splat(HI), $m::max(splat(LO), x));
                let n = $m::round($m::mul(x, splat(LOG2E)));
                let r = $m::fnma(n, splat(LN2_LO), $m::fnma(n, splat(LN2_HI), x));
                let mut p = splat(P[0]);
                for &c in &P[1..] {
                    p = $m::fma(p, r, splat(c));
                }
                $m::scale(p, n)
            }
        }

        impl<const R: usize> ::std::fmt::Debug for $T<R> {
            fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
                f.debug_list().entries(self.regs().iter().flatten()).finish()
            }
        }
        impl<const R: usize> PartialEq for $T<R> {
            fn eq(&self, o: &Self) -> bool {
                self.regs() == o.regs()
            }
        }
        impl<const R: usize> From<f64> for $T<R> {
            #[inline(always)]
            fn from(k: f64) -> Self {
                Self([$m::splat(k as $e); R])
            }
        }

        impl<const R: usize> ::std::ops::Add for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn add(self, o: Self) -> Self {
                self.zip(o, $m::add)
            }
        }
        impl<const R: usize> ::std::ops::Sub for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn sub(self, o: Self) -> Self {
                self.zip(o, $m::sub)
            }
        }
        impl<const R: usize> ::std::ops::Mul for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn mul(self, o: Self) -> Self {
                self.zip(o, $m::mul)
            }
        }
        impl<const R: usize> ::std::ops::Div for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn div(self, o: Self) -> Self {
                self.zip(o, $m::div)
            }
        }
        impl<const R: usize> ::std::ops::Neg for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn neg(self) -> Self {
                self.map($m::neg)
            }
        }
        impl<const R: usize> ::std::ops::Add<f64> for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn add(self, k: f64) -> Self {
                self + Self::from(k)
            }
        }
        impl<const R: usize> ::std::ops::Sub<f64> for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn sub(self, k: f64) -> Self {
                self - Self::from(k)
            }
        }
        impl<const R: usize> ::std::ops::Mul<f64> for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn mul(self, k: f64) -> Self {
                self * Self::from(k)
            }
        }
        impl<const R: usize> ::std::ops::Div<f64> for $T<R> {
            type Output = Self;
            #[inline(always)]
            fn div(self, k: f64) -> Self {
                self / Self::from(k)
            }
        }
        impl<const R: usize> ::std::ops::AddAssign for $T<R> {
            #[inline(always)]
            fn add_assign(&mut self, o: Self) {
                *self = *self + o;
            }
        }
        impl<const R: usize> ::std::ops::SubAssign for $T<R> {
            #[inline(always)]
            fn sub_assign(&mut self, o: Self) {
                *self = *self - o;
            }
        }

        impl<const R: usize> $crate::AdNum for $T<R> {
            #[inline(always)]
            fn exp(self) -> Self {
                self.map(Self::exp_reg)
            }
            #[inline(always)]
            fn ln(self) -> Self {
                self.per_lane($e::ln)
            }
            #[inline(always)]
            fn sqrt(self) -> Self {
                self.map($m::sqrt)
            }
            #[inline(always)]
            fn powf(self, k: f64) -> Self {
                self.per_lane(|x| x.powf(k as $e))
            }
            #[inline(always)]
            fn relu(self) -> Self {
                let z = $m::splat(0.0);
                self.map(|a| $m::max(z, a))
            }
            #[inline(always)]
            fn detach(self) -> Self {
                self
            }
            #[inline(always)]
            fn select_gt(a: Self, b: Self, x: Self, y: Self) -> Self {
                Self(::std::array::from_fn(|i| $m::sel_gt(a.0[i], b.0[i], x.0[i], y.0[i])))
            }
            #[inline(always)]
            fn rsub(self, k: f64) -> Self {
                Self::from(k) - self
            }
            #[inline(always)]
            fn rdiv(self, k: f64) -> Self {
                Self::from(k) / self
            }
        }

        impl<const R: usize> $crate::Real for $T<R> {
            type Lanes = Self;
            #[inline(always)]
            fn lift(v: Self) -> Self {
                v
            }
            #[inline(always)]
            fn value(self) -> Self {
                self
            }
            #[inline(always)]
            fn tangent(self) -> Self {
                Self::from(0.0)
            }
            #[inline(always)]
            fn mul_add(self, b: Self, c: Self) -> Self {
                Self(::std::array::from_fn(|i| $m::fma(self.0[i], b.0[i], c.0[i])))
            }
            #[inline(always)]
            fn nmul_add(self, b: Self, c: Self) -> Self {
                Self(::std::array::from_fn(|i| $m::fnma(self.0[i], b.0[i], c.0[i])))
            }
            #[inline(always)]
            fn neg_zero() -> Self {
                Self([$m::splat(-0.0); R])
            }
            #[inline]
            fn per_lane(f: impl Fn(usize) -> Self) -> Self {
                <Self as $crate::lanes::Lanes>::from_fn(|l| $crate::lanes::Lanes::lane(f(l), l))
            }
        }

        impl<const R: usize> $crate::lanes::Lanes for $T<R> {
            type Elem = $e;
            const W: usize = $n * R;
            #[inline(always)]
            fn load(src: &[$e]) -> Self {
                assert!(src.len() >= Self::W);
                Self(::std::array::from_fn(|i| unsafe { $m::load(src.as_ptr().add($n * i)) }))
            }
            #[inline(always)]
            fn load_f32(src: &[f32]) -> Self {
                assert!(src.len() >= Self::W);
                Self(::std::array::from_fn(|i| unsafe { $m::load_f32(src.as_ptr().add($n * i)) }))
            }
            #[inline(always)]
            fn store(self, dst: &mut [$e]) {
                assert!(dst.len() >= Self::W);
                for (i, r) in self.0.iter().enumerate() {
                    unsafe { $m::store(dst.as_mut_ptr().add($n * i), *r) };
                }
            }
            #[inline(always)]
            fn lane(self, i: usize) -> f64 {
                self.regs()[i / $n][i % $n] as f64
            }
            #[inline(always)]
            fn from_fn(mut f: impl FnMut(usize) -> f64) -> Self {
                Self(::std::array::from_fn(|r| {
                    let a: [$e; $n] = ::std::array::from_fn(|l| f($n * r + l) as $e);
                    unsafe { $m::load(a.as_ptr()) }
                }))
            }
            #[inline(always)]
            fn sum(self) -> f64 {
                self.regs().iter().flatten().map(|&x| x as f64).sum()
            }
        }
    };
}
