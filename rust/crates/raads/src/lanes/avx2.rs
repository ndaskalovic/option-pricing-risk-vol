//! AVX2 + FMA packs: `F32<R>` = R × `__m256` (8R lanes), `F64<R>` = R × `__m256d` (4R lanes),
//! and the 128-bit `F32h<R>` = R × `__m128` (4R lanes), `F64h<R>` = R × `__m128d` (2R lanes)
//! for packs narrower than a 256-bit register.
//!
//! Compiled only when `avx2` and `fma` are enabled for the whole crate (e.g.
//! `-C target-cpu=x86-64-v3`, `-C target-cpu=native` or `-C target-feature=+avx2,+fma`), so
//! every intrinsic inlines into its caller and the `unsafe` blocks around them are sound: the
//! binary already requires the features. There is no runtime dispatch.
//!
//! The pack types are generated by [`x86_pack!`] from a module of register ops per vector type
//! (`m128`, `m128d`, `m256`, `m256d`); `avx512` reuses the macro.

#![allow(unused_unsafe)]

/// `1.5·2^52`: adding it to an integral `f64` puts the integer in the low mantissa bits
/// (AVX2 has no `f64 → i64` conversion).
const MAGIC_F64: f64 = 6_755_399_441_055_744.0;

/// Round to nearest (ties to even), without raising exceptions.
pub(super) const NEAREST: i32 = core::arch::x86_64::_MM_FROUND_TO_NEAREST_INT | core::arch::x86_64::_MM_FROUND_NO_EXC;

/// Register ops for `__m128` (4 × `f32`).
mod m128 {
    pub use crate::lanes::exp_poly::f32::bits as exp;
    use core::arch::x86_64::*;
    pub type V = __m128;
    #[inline(always)]
    pub fn splat(k: f32) -> V {
        unsafe { _mm_set1_ps(k) }
    }
    #[inline(always)]
    pub unsafe fn load(p: *const f32) -> V {
        unsafe { _mm_loadu_ps(p) }
    }
    #[inline(always)]
    pub unsafe fn load_f32(p: *const f32) -> V {
        unsafe { _mm_loadu_ps(p) }
    }
    #[inline(always)]
    pub unsafe fn store(p: *mut f32, a: V) {
        unsafe { _mm_storeu_ps(p, a) }
    }
    #[inline(always)]
    pub fn add(a: V, b: V) -> V {
        unsafe { _mm_add_ps(a, b) }
    }
    #[inline(always)]
    pub fn sub(a: V, b: V) -> V {
        unsafe { _mm_sub_ps(a, b) }
    }
    #[inline(always)]
    pub fn mul(a: V, b: V) -> V {
        unsafe { _mm_mul_ps(a, b) }
    }
    #[inline(always)]
    pub fn div(a: V, b: V) -> V {
        unsafe { _mm_div_ps(a, b) }
    }
    #[inline(always)]
    pub fn neg(a: V) -> V {
        unsafe { _mm_xor_ps(a, splat(-0.0)) }
    }
    #[inline(always)]
    pub fn fma(a: V, b: V, c: V) -> V {
        unsafe { _mm_fmadd_ps(a, b, c) }
    }
    #[inline(always)]
    pub fn fnma(a: V, b: V, c: V) -> V {
        unsafe { _mm_fnmadd_ps(a, b, c) }
    }
    #[inline(always)]
    pub fn sqrt(a: V) -> V {
        unsafe { _mm_sqrt_ps(a) }
    }
    #[inline(always)]
    pub fn min(a: V, b: V) -> V {
        unsafe { _mm_min_ps(a, b) }
    }
    #[inline(always)]
    pub fn max(a: V, b: V) -> V {
        unsafe { _mm_max_ps(a, b) }
    }
    #[inline(always)]
    pub fn sel_gt(a: V, b: V, x: V, y: V) -> V {
        unsafe { _mm_blendv_ps(y, x, _mm_cmp_ps::<_CMP_GT_OQ>(a, b)) }
    }
    #[inline(always)]
    pub fn round(a: V) -> V {
        unsafe { _mm_round_ps::<{ super::NEAREST }>(a) }
    }
    /// `p·2^(n-1)` through the exponent bits (`exp_poly` `bits`).
    #[inline(always)]
    pub fn scale(p: V, n: V) -> V {
        unsafe { mul(p, _mm_castsi128_ps(_mm_slli_epi32::<23>(_mm_add_epi32(_mm_cvtps_epi32(n), _mm_set1_epi32(126))))) }
    }
}

